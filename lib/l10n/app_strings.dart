/// Translate a key to the given language.
/// Falls back to English, then to the key itself.
String tr(String key, String lang) {
  return appStrings[key]?[lang] ?? appStrings[key]?['en'] ?? key;
}

/// Get time-based greeting for a language.
String getGreeting(String lang) {
  final hour = DateTime.now().hour;
  if (hour >= 5 && hour < 12) return tr('greeting_morning', lang);
  if (hour >= 12 && hour < 17) return tr('greeting_afternoon', lang);
  if (hour >= 17 && hour < 21) return tr('greeting_evening', lang);
  return tr('greeting_night', lang);
}